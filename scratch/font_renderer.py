def render_text_to_segments(text, start_x, start_y, char_height=1.2, char_width=0.8, spacing=0.3):
    """
    Renders text to line segments [(x1, y1, x2, y2), ...]
    start_x, start_y is bottom-left origin of first character.
    """
    segments = []
    curr_x = start_x
    scale_y = char_height / 7.0
    scale_x = char_width / 4.0

    for ch in text.upper():
        strokes = FONT_STROKES.get(ch, [])
        for (p1, p2) in strokes:
            x1 = curr_x + p1[0] * scale_x
            y1 = start_y + p1[1] * scale_y
            x2 = curr_x + p2[0] * scale_x
            y2 = start_y + p2[1] * scale_y
            segments.append((x1, y1, x2, y2))
        curr_x += char_width + spacing
    return segments

