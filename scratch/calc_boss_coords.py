# Note: The solid of revolution is rotate_extrude() of the profile in (R, Z) plane.
# That means for any point (X, Y, Z), radius R_horizontal = sqrt(X^2 + Y^2).
# Wait! In rotate_extrude around Z axis:
# R = sqrt(X^2 + Y^2), and Z is Z!
# So for any (X, Z), what is Y on the inner surface?
# R^2 = X^2 + Y^2 => Y^2 = R(Z)^2 - X^2!
# Let's find R(Z) from inner_profile for Z = 26.0 and Z = -23.0!

def get_r_at_z(profile, target_z):
    for i in range(len(profile)-1):
        r1, z1 = profile[i]
        r2, z2 = profile[i+1]
        if min(z1, z2) <= target_z <= max(z1, z2):
            t = (target_z - z1) / (z2 - z1)
            return r1 + t * (r2 - r1)
    return None

for pt in screw_pts:
    x, z = pt
    r_inner = get_r_at_z(inner_profile, z)
    r_outer = get_r_at_z(outer_profile, z)
    # If R = sqrt(X^2 + Y^2), then |Y| = sqrt(R^2 - X^2)
    y_inner = math.sqrt(max(0, r_inner**2 - x**2)) if r_inner and r_inner >= abs(x) else None
    y_outer = math.sqrt(max(0, r_outer**2 - x**2)) if r_outer and r_outer >= abs(x) else None
    print(f"Point ({x}, {z}):")
    print(f"  R_inner(Z={z}) = {r_inner:.2f}, R_outer(Z={z}) = {r_outer:.2f}")
    print(f"  Wall starts at Y_inner = -{y_inner:.2f}, outer at Y_outer = -{y_outer:.2f}")
